// 视觉验收：首页(真图封面) → 详情页(图集/内容/评价)
import automator from 'miniprogram-automator'
import path from 'node:path'
const log = (...a) => console.log('[shot]', ...a)
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const mini = await automator.connect({ wsEndpoint: 'ws://127.0.0.1:9421' })
let page = await mini.reLaunch('/pages/home/index')
await wait(2200)
await mini.screenshot({ path: path.join('./automator-shots', 'v2-home.png') })
const item = await page.$('.tour-item')
await item.tap()
await wait(2500)
await mini.screenshot({ path: path.join('./automator-shots', 'v2-detail-top.png') })
// 滚动到内容/评价区截图
page = await mini.currentPage()
await page.callMethod('setData', { scrollTo: '' }).catch(() => {})
const el = await page.$('.rating-row')
log('评分行存在:', !!el)
const covers = await page.$$('.gallery swiper-item')
log('图集张数:', covers.length)
// 用 pageScrollTo 看下半部
await mini.pageScrollTo(1400).catch((e) => log('scroll err', e.message))
await wait(600)
await mini.screenshot({ path: path.join('./automator-shots', 'v2-detail-mid.png') })
await mini.pageScrollTo(2600).catch(() => {})
await wait(600)
await mini.screenshot({ path: path.join('./automator-shots', 'v2-detail-bottom.png') })
log('DONE')
process.exit(0)
