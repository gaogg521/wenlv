-- 官方补贴独立域，金额分；不修改旅豆余额/账本/历史封存。
CREATE TABLE freedom_budget (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 total BIGINT NOT NULL,
 committed BIGINT NOT NULL DEFAULT 0,
 used BIGINT NOT NULL DEFAULT 0,
 status TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CHECK(total>0 AND committed>=0 AND used>=0 AND committed+used<=total)
) ENGINE=InnoDB;
CREATE TABLE freedom_template (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 budget_id BIGINT UNSIGNED NOT NULL,
 rule_json JSON NOT NULL,
 version INT NOT NULL DEFAULT 1,
 status TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE freedom_batch (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 request_key VARCHAR(64) NOT NULL UNIQUE,
 payload_hash VARCHAR(64) NOT NULL,
 template_id BIGINT UNSIGNED NOT NULL,
 recipients JSON NOT NULL,
 operator VARCHAR(64) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE freedom_right (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 batch_id BIGINT UNSIGNED NOT NULL,
 template_id BIGINT UNSIGNED NOT NULL,
 budget_id BIGINT UNSIGNED NOT NULL,
 rule_json JSON NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'available',
 order_no VARCHAR(32) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_batch_user(batch_id,user_id),
 KEY idx_user(user_id,status)
) ENGINE=InnoDB;
CREATE TABLE freedom_event (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 budget_id BIGINT UNSIGNED NOT NULL,
 right_id BIGINT UNSIGNED NOT NULL,
 kind VARCHAR(24) NOT NULL,
 amount BIGINT NOT NULL,
 biz_ref VARCHAR(80) NOT NULL,
 detail VARCHAR(300) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_biz(biz_ref,kind)
) ENGINE=InnoDB;
CREATE TABLE freedom_order (
 order_no VARCHAR(32) PRIMARY KEY,
 right_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 merchant_id BIGINT UNSIGNED NOT NULL,
 goods BIGINT NOT NULL,
 discount BIGINT NOT NULL,
 cash_pay BIGINT NOT NULL,
 rule_json JSON NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'locked',
 paid_subsidy BIGINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE freedom_payment (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_no VARCHAR(32) NOT NULL,
 direction TINYINT NOT NULL,
 amount BIGINT NOT NULL,
 pay_ref VARCHAR(64) NOT NULL UNIQUE,
 receipt_url VARCHAR(512) NOT NULL,
 reason VARCHAR(300) NOT NULL,
 operator VARCHAR(64) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
